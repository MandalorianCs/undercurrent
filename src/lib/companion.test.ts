/**
 * Проверка распознавания кризисных сигналов.
 *
 * Запуск: npm run test:crisis
 *
 * Почему этот файл существует. Шаблоны здесь однажды уже молчали
 * целиком — семь из восьми не совпадали ни с чем из-за `\b` перед
 * кириллицей, и заметить это по коду было невозможно: он выглядел
 * абсолютно рабочим. Сломаться так же тихо он может снова, а цена
 * молчания — человек, написавший о желании умереть, получает ответ про
 * рабочую нагрузку.
 *
 * Здесь нет фреймворка намеренно: Node 24 исполняет TypeScript сам, и
 * проверка должна запускаться одной командой без установки чего-либо.
 */

import { extractMarkers, isCrisis, respond } from './companion.ts';

let failures = 0;

function check(label: string, actual: unknown, expected: unknown) {
  const ok = JSON.stringify(actual) === JSON.stringify(expected);
  if (!ok) failures++;
  console.log(`  ${ok ? 'ok    ' : 'ПРОВАЛ'} — ${label}${ok ? '' : `  (получено: ${JSON.stringify(actual)})`}`);
}

// ── Кризис: должно срабатывать ────────────────────────────────
console.log('\n▸ кризисные сигналы — должны распознаваться');
for (const phrase of [
  'я больше не хочу жить',
  'не хочу жить',
  'жить не хочется совсем',
  'жить больше не могу',
  'не вижу смысла жить',
  'нет смысла жить дальше',
  'мне незачем жить',
  'думаю покончить с собой',
  'хочу свести счёты с жизнью',
  'думаю уйти из жизни',
  'иногда думаю про суицид',
  'читал про самоубийства',
  'хочу умереть',
  'хочется просто сдохнуть',
  'лучше бы я умерла',
  'лучше бы меня не было',
  'хочу не проснуться завтра',
  'иногда хочу навредить себе',
  'я режу себя',
  'вчера порезала себя',
  'устал жить',
]) {
  check(phrase, isCrisis(phrase), true);
}

// ── Кризис: не должно срабатывать ─────────────────────────────
//
// Здесь только фразы, где ошибка обрывала бы нормальный разговор.
// Список намеренно короткий: при сомнении шаблон должен срабатывать.
console.log('\n▸ обычная тяжесть — кризисом считаться не должна');
for (const phrase of [
  'я очень устал на работе',
  'хочу уволиться, сил больше нет',
  'начальник орёт на меня каждый день',
  'не хочу идти завтра в офис',
  'не хочу жить с родителями',
  'устал жить в общежитии',
  'не вижу смысла в этих отчётах',
  'работаю по ночам, сплю по четыре часа',
]) {
  check(phrase, isCrisis(phrase), false);
}

// ── Кризис обрывает обычный сценарий ──────────────────────────
console.log('\n▸ ответ на кризис');
{
  const text = 'я больше не хочу жить';
  const markers = extractMarkers(text);
  const reply = respond(text, markers, 0);
  check('ответ отличается от обычного', reply.includes('живой человек'), true);
  check('не спрашивает про нагрузку', /нагрузк|задач|дедлайн/i.test(reply), false);
}

// ── Маркеры ───────────────────────────────────────────────────
console.log('\n▸ извлечение маркеров');
{
  const m = extractMarkers('я совсем вымотался, работаю по ночам, начальник орёт');
  check('истощение найдено', typeof m?.exhaustion === 'number', true);
  check('нагрузка найдена', typeof m?.workload === 'number', true);
  check('конфликт найден', typeof m?.conflict === 'number', true);
  check('теги проставлены', Array.isArray(m?.tags) && m!.tags!.length > 0, true);
}
{
  check('нейтральная фраза не даёт маркеров', extractMarkers('спасибо, доброе утро'), null);
}
{
  const one = extractMarkers('устал');
  const many = extractMarkers('устал, вымотан, сил нет, выгорел');
  check(
    'больше совпадений — выше оценка',
    (many?.exhaustion ?? 0) > (one?.exhaustion ?? 0),
    true,
  );
  check('оценка не превышает 1', (many?.exhaustion ?? 0) <= 1, true);
}

// ── Итог ──────────────────────────────────────────────────────
console.log();
if (failures > 0) {
  console.log(`✗ Провалов: ${failures}`);
  process.exit(1);
}
console.log('✓ Распознавание кризиса и маркеров работает.');
