/**
 * ИИ-слой Undercurrent на этапе MVP.
 *
 * Архитектура здесь та же, что заявлена в питче: ответы не сочиняются
 * свободно, а собираются из курируемой базы одобренных формулировок.
 * Отличие только в том, что сейчас база лежит в этом файле, а не в
 * векторном хранилище: подключение настоящего RAG меняет реализацию
 * `respond`, но не её место в системе.
 *
 * Почему не свободная генерация. Ответ на «я больше не могу» — это не
 * задача про красивый текст. Формулировку, которую увидит человек в
 * плохом состоянии, должен утверждать специалист, а не выбирать модель
 * по правдоподобию. Курируемая база означает, что список того, что
 * продукт вообще способен сказать, конечен и его можно вычитать.
 */

import type { StressMarkers } from './types';

// ─────────────────────────────────────────────────────────────
// Кризисные сигналы
//
// Это первая проверка, и она обрывает обычный сценарий. Продукт про
// выгорание рано или поздно получит сообщение о суициде, и ответить на
// него разбором рабочей нагрузки — значит навредить. Здесь нет
// «оценки риска» и градаций: любое совпадение уводит в живой контакт.
// ─────────────────────────────────────────────────────────────

const CRISIS_PATTERNS: RegExp[] = [
  /\bне\s*хочу\s*жить\b/i,
  /\bне\s*вижу\s*смысла\s*(жить|дальше)\b/i,
  /\b(покончить|покончу)\s*с\s*собой\b/i,
  /\bсуицид|самоубийств/i,
  /\bлучше\s*бы\s*(я\s*)?(умер|умерла|меня\s*не\s*было)\b/i,
  /\bне\s*проснуться\b/i,
  /\bсебе\s*(вред|навредить)\b/i,
  /\bрежу\s*себя\b/i,
];

export function isCrisis(text: string): boolean {
  return CRISIS_PATTERNS.some((p) => p.test(text));
}

/**
 * Номер кризисной линии.
 *
 * НАМЕРЕННО не зашит в код. Ошибиться здесь хуже, чем не показать
 * ничего: человек в кризисе наберёт то, что написано, и попадёт не туда.
 * Значение подставляется из .env после того, как номер проверен по
 * официальному источнику.
 */
export const CRISIS_LINE = process.env.EXPO_PUBLIC_CRISIS_LINE ?? null;

export const CRISIS_REPLY =
  'Я останавливаюсь здесь, потому что дальше нужен живой человек, а не я.\n\n' +
  'То, что вы написали, — это не то, с чем стоит оставаться одному. ' +
  'Пожалуйста, свяжитесь с человеком прямо сейчас: с тем, кому доверяете, ' +
  'или со специалистом по контакту ниже.\n\n' +
  'Я никуда не денусь и буду здесь, когда вы вернётесь.';

// ─────────────────────────────────────────────────────────────
// Извлечение маркеров
//
// Ровно этот объект — всё, что покидает переписку. Текст остаётся в
// messages и не уходит ни в агрегаты, ни куда-либо ещё.
//
// Словарь русский и разговорный: люди пишут «задолбался», а не
// «испытываю эмоциональное истощение». Отдельно учтён казахстанский
// рабочий сленг — «горит дедлайн», «завал», «на созвонах весь день».
// ─────────────────────────────────────────────────────────────

/** Числовые оси. `tags` сюда не входит — это список тем, а не оценка. */
type NumericAxis = 'exhaustion' | 'workload' | 'hopelessness' | 'conflict';

type Lexicon = { axis: NumericAxis; weight: number; patterns: RegExp[] };

const LEXICONS: Lexicon[] = [
  {
    axis: 'exhaustion',
    weight: 0.34,
    patterns: [
      /устал|устала|усталость|вымотан|вымотал/i,
      /задолбал|заебал|достало|сил\s*нет|нет\s*сил/i,
      /не\s*сплю|сплю\s*по\s*\d|бессонниц|недосып/i,
      /выгорел|выгорание|опустош/i,
    ],
  },
  {
    axis: 'workload',
    weight: 0.28,
    patterns: [
      /перераб|овертайм|сверхуроч/i,
      /завал|заваливают|горит\s*дедлайн|дедлайн/i,
      /работаю\s*(по\s*)?(ночам|выходным|вечерам)/i,
      /чуж(ие|ую)\s*задач|за\s*двоих|за\s*троих/i,
      /весь\s*день\s*на\s*(созвон|встреч)/i,
    ],
  },
  {
    axis: 'hopelessness',
    weight: 0.2,
    patterns: [
      /(нет|никакого)\s*смысла|бессмысленн/i,
      /ничего\s*не\s*ме?н?яется|всё\s*равно\s*не/i,
      /хочу\s*уволит|хочу\s*уйти|думаю\s*об\s*уходе/i,
      /руки\s*опуска/i,
    ],
  },
  {
    axis: 'conflict',
    weight: 0.18,
    patterns: [
      /руководител|начальник|шеф|директор.*(орёт|кричит|давит)/i,
      /(орёт|кричит|унижа|обесценива|давит)/i,
      /конфликт|поссорил|токсич/i,
      /не\s*слышат|не\s*слушают|игнорируют/i,
    ],
  },
];

/** Ярлыки для HR-дашборда: обезличенные темы, без цитат. */
const TAG_PATTERNS: Array<[RegExp, string]> = [
  [/перераб|овертайм|работаю\s*(по\s*)?(ночам|выходным)/i, 'переработки'],
  [/дедлайн|завал|срок/i, 'сроки'],
  [/руководител|начальник|шеф/i, 'отношения с руководителем'],
  [/зарплат|деньги|повышени/i, 'вознаграждение'],
  [/не\s*сплю|бессонниц|недосып/i, 'сон'],
  [/уволит|уйти|ухода/i, 'намерение уйти'],
  [/отпуск|выходн/i, 'отдых'],
];

/**
 * Насыщение по числу совпадений: одно упоминание усталости — 0.5,
 * два — 0.75, три и больше — ближе к 1.
 *
 * Линейный счёт «каждое совпадение +0.3» давал бы 1.0 за длинное
 * сообщение, где слово «устал» встретилось трижды в одном абзаце, —
 * а это одна мысль, а не тройная тяжесть.
 */
function saturate(hits: number): number {
  if (hits <= 0) return 0;
  return Number((1 - Math.pow(0.5, hits)).toFixed(2));
}

export function extractMarkers(text: string): StressMarkers | null {
  const markers: StressMarkers = {};
  let any = false;

  for (const { axis, patterns } of LEXICONS) {
    const hits = patterns.filter((p) => p.test(text)).length;
    if (hits > 0) {
      markers[axis] = saturate(hits);
      any = true;
    }
  }

  const tags = TAG_PATTERNS.filter(([p]) => p.test(text)).map(([, tag]) => tag);
  if (tags.length) {
    markers.tags = tags;
    any = true;
  }

  // null, а не пустой объект: сообщение без маркеров не должно попадать
  // в расчёт среднего. Иначе «спасибо» и «доброе утро» тянули бы риск
  // отдела вниз и маскировали тех, кому тяжело.
  return any ? markers : null;
}

// ─────────────────────────────────────────────────────────────
// Курируемые ответы
//
// Каждый ответ привязан к оси, по которой он уместен. Внутри оси
// выбирается по числу уже сказанного, чтобы человек не получал одну и
// ту же фразу дважды подряд — повтор мгновенно выдаёт автомат и обрывает
// доверие к разговору.
// ─────────────────────────────────────────────────────────────

const REPLIES: Record<string, string[]> = {
  exhaustion: [
    'Похоже, вы держитесь на исходе. Скажите, когда вы последний раз отдыхали так, чтобы не думать о работе?',
    'Усталость, которая не проходит после выходных, — это уже не про сон. Что забирает больше всего сил: объём или ощущение, что это не закончится?',
    'Вы описываете состояние, когда ресурс уже потрачен, а требования те же. Что из текущих задач вы могли бы не делать неделю — и что случилось бы?',
  ],
  workload: [
    'Объём, который вы описываете, обычно не помещается в рабочий день ни у кого. Это временный пик или так уже несколько месяцев?',
    'Давайте разложим: что из этого ваша зона, а что доехало до вас, потому что больше некому?',
    'Когда задач больше, чем времени, выбор всё равно происходит — просто молча и в ущерб вам. Что вы выбрали бы вслух?',
  ],
  hopelessness: [
    'Ощущение, что ничего не изменится, тяжелее самой нагрузки. Было что-то, что вы пробовали изменить, и это не сработало?',
    'Мысли об уходе часто появляются раньше, чем решение. Это способ представить выход — или вы уже всерьёз считаете сроки?',
    'Вы говорите так, будто выбора нет. Давайте проверим: какие варианты вы вообще рассматривали, даже те, что отбросили сразу?',
  ],
  conflict: [
    'Когда тебя не слышат, нагрузка перестаёт быть просто нагрузкой. Это происходит со всеми в команде или адресно с вами?',
    'Расскажите, как обычно выглядит такой разговор — с чего он начинается?',
    'Вы описываете ситуацию, где договориться не выходит. Что вы уже пробовали сказать, и чем это закончилось?',
  ],
  neutral: [
    'Я здесь и слушаю. Расскажите подробнее — что происходит?',
    'Спасибо, что написали. С чего вам самим хочется начать?',
    'Давайте по порядку. Что беспокоит сильнее всего прямо сейчас?',
  ],
};

/**
 * Ответ собеседника.
 *
 * `turn` — номер реплики в разговоре, нужен для выбора без повторов.
 * Никакой памяти между разговорами нет и не будет: она означала бы
 * профиль человека, а профиля здесь быть не должно.
 */
export function respond(text: string, markers: StressMarkers | null, turn: number): string {
  if (isCrisis(text)) return CRISIS_REPLY;

  // Порядок — приоритет по тяжести, а не по величине оценки:
  // безнадёжность важнее объёма задач, даже если словарь насчитал по ней
  // меньше совпадений.
  const axes: NumericAxis[] = ['hopelessness', 'conflict', 'exhaustion', 'workload'];

  const leading = axes.find((axis) => (markers?.[axis] ?? 0) >= 0.5);

  const pool = REPLIES[leading ?? 'neutral'] ?? REPLIES.neutral;
  return pool[turn % pool.length];
}
