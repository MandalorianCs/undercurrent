/**
 * ИИ-слой Undercurrent на этапе MVP.
 *
 * Архитектура здесь та же, что заявлена в питче: ответы не сочиняются
 * свободно, а собираются из курируемой базы одобренных формулировок.
 * Отличие только в том, что сейчас база лежит в этом файле, а не в
 * векторном хранилище: подключение настоящего RAG меняет реализацию
 * `respond`, но не её место в системе.
 *
 * Почему не свободная генерация. Ответ на «я больше не могу» — это не
 * задача про красивый текст. Формулировку, которую увидит человек в
 * плохом состоянии, должен утверждать специалист, а не выбирать модель
 * по правдоподобию. Курируемая база означает, что список того, что
 * продукт вообще способен сказать, конечен и его можно вычитать.
 */

import type { StressMarkers } from './types';

// ─────────────────────────────────────────────────────────────
// Кризисные сигналы
//
// Это первая проверка, и она обрывает обычный сценарий. Продукт про
// выгорание рано или поздно получит сообщение о суициде, и ответить на
// него разбором рабочей нагрузки — значит навредить. Здесь нет
// «оценки риска» и градаций: любое совпадение уводит в живой контакт.
// ─────────────────────────────────────────────────────────────

/**
 * ⚠ НИ ОДНОГО `\b` В ЭТИХ ШАБЛОНАХ.
 *
 * В JavaScript `\b` определён через `\w`, а `\w` — это `[A-Za-z0-9_]`,
 * только латиница. Перед кириллической буквой граница слова не
 * возникает никогда, и шаблон вида /\bне хочу жить/ не совпадает ни с
 * чем. Ровно на этом здесь однажды сломалось распознавание целиком:
 * семь шаблонов из восьми молчали, а выглядели рабочими.
 *
 * Правая граница, где она нужна, делается явным `(?!…)`.
 *
 * ── Асимметрия ошибок ────────────────────────────────────────
 * Ложное срабатывание: человеку, написавшему «не хочу жить с
 * родителями», показали телефон доверия. Неловко, он листает дальше.
 *
 * Пропуск: человек написал, что не хочет жить, и получил бодрый вопрос
 * про рабочую нагрузку.
 *
 * Цена этих ошибок несопоставима, поэтому шаблоны намеренно
 * чувствительные. Сужать их можно только с очень хорошим основанием.
 */

// «жить» часто продолжается предлогом — «жить с родителями», «жить в
// общаге», «жить на две страны». Это про быт, а не про желание умереть.
const NOT_ABOUT_LIVING_SOMEWHERE = '(?!\\s*(с|со|в|во|у|на|над|под|за|рядом|вместе|здесь|там|тут|как|по|ради))';

const CRISIS_PATTERNS: RegExp[] = [
  // Прямое высказывание о нежелании жить
  new RegExp('не\\s*хочу\\s*(больше\\s*)?жить' + NOT_ABOUT_LIVING_SOMEWHERE, 'i'),
  new RegExp('(устал|устала|надоело)\\s*жить' + NOT_ABOUT_LIVING_SOMEWHERE, 'i'),
  /жить\s*(больше\s*)?не\s*(хочу|хочется|могу)/i,
  /(не\s*вижу|нет)\s*смысла\s*(жить|дальше|существовать)/i,
  /(не\s*для\s*чего|незачем|не\s*зачем)\s*жить/i,

  // Намерение
  /(покончить|покончу|покончил|покончила)\s*с\s*собой/i,
  /(свести|сведу)\s*счёты\s*с\s*жизнью/i,
  /(свести|сведу)\s*счеты\s*с\s*жизнью/i,
  /уйти\s*из\s*жизни/i,
  /суицид|самоубийств/i,

  // Желание смерти.
  //
  // Между «хочется» и «сдохнуть» помещаются слова — «хочется просто
  // сдохнуть», «хочу уже умереть». Ограничиваем разрыв двадцатью
  // символами без знаков конца предложения, чтобы совпадение не
  // перепрыгивало из одной фразы в другую.
  /хоч(у|ется)[^.!?]{0,20}(умереть|сдохнуть|исчезнуть)/i,
  /лучше\s*бы\s*(я\s*)?(умер|умерла|сдох|сдохла|меня\s*не\s*было|не\s*родил)/i,
  /(хочу\s*)?не\s*(проснуться|просыпаться)/i,

  // Самоповреждение.
  //
  // [а-яё], а не \w: \w — только латиница, и «режу» после «реж» не
  // продолжится. Та же ловушка, что убила прошлую версию этого списка.
  /себе\s*(вред|навредить)|навредить\s*себе/i,
  /(реж|резал|резала|порезал|порезала)[а-яё]*\s*себя/i,
];

export function isCrisis(text: string): boolean {
  return CRISIS_PATTERNS.some((p) => p.test(text));
}

