-- Удаление истории не должно отбирать доступ.
--
-- Прежняя версия delete_my_data удаляла строку anonymous_sessions и
-- полагалась на каскады. Каскады отрабатывали правильно, но вместе с
-- перепиской исчезала и сама сессия — то есть доступ к продукту.
--
-- В комментарии к той версии было написано «человек не теряет доступ»,
-- и рассуждение шло про employee_access: право на вход действительно не
-- трогалось. Но доступ к приложению даёт не запись в employee_access, а
-- строка сессии, и удалялась именно она.
--
-- Что это означало на практике:
--
--   • сотрудник B2B терял привязку к компании и должен был идти за новым
--     билетом — при том, что экран обещает «доступ сохранится»;
--   • подписчик B2C оказывался в состоянии «вошёл, но сессии нет» и
--     попадал на экран корпоративного входа, которого в глаза не видел.
--
-- Для продукта, где «удалиться» не должно выглядеть событием ни для
-- работодателя, ни для самого человека, это прямое нарушение обещания.
--
-- Теперь удаляем содержимое, а не контейнер.

create or replace function delete_my_data()
returns void
language sql
volatile
set search_path = public
as $$
  -- Сообщения уходят каскадом от разговоров, поэтому явно их не трогаем.
  delete from conversations where anonymous_session_id = auth.uid();
  delete from mood_entries   where session_id = auth.uid();
$$;

comment on function delete_my_data() is
  'Удаляет разговоры и дневник, сохраняя саму сессию: удаление истории '
  'не отбирает доступ к продукту и не выглядит событием со стороны.';
